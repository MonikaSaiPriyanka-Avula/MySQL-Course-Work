-- Absolute value
select abs(-25), abs(30);

-- Ceiling / Round up
select ceil(12.3), ceil(-12.7);

-- Floor / Round down
select floor(12.9), floor(-12.3);

-- Power / Exponent
select pow(2,3), pow(5,2);

-- Square Root
select sqrt(16), sqrt(2);

-- pi constant
select pi();

-- Modulus / Remainder
select mod(10,3);

-- sign
select sign(-25), sign(0), sign(30);

-- Round
select round(123.4567,2), round(123.4567,3);

-- Truncate
select truncate(123.4567,2), truncate(123.4567,3);

-- Random Number
select rand(), rand(10);

-- Greatest
select greatest(100,250,89,76);

-- Least
select least(9,87,45,23);


